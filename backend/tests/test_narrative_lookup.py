def record(name, passed, detail=""):
    RESULTS.append((name, passed, detail))
    status = "PASS" if passed else "FAIL"
    print(f"[{status}] {name}" + (f" -- {detail}" if detail else ""))


def narrative(text, company, form="10-K", filing="filing.txt"):
    return {
        "text": text,
        "metadata": {
            "type": "narrative",
            "company": company,
            "form": form,
            "filing": filing,
            "source": "SEC EDGAR",
        },
    }


def table(text, company, scale="million"):
    return {
        "text": text,
        "metadata": {
            "type": "table",
            "company": company,
            "form": "10-K",
            "filing": "table.html",
            "source": "SEC EDGAR",
            "statement_scale": scale,
        },
    }


