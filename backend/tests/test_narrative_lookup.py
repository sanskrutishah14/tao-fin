def test_negative_and_synthetic():
    apple = narrative(APPLE_SENTENCE, "AAPL")
    found = resolve_narrative_question(APPLE, [apple], COMPANIES)
    record(
        "combined cash total uses the stated narrative amount",
        found and found["status"] == "answered" and found["value"] == 132.4 and found["unit"] == "billion",
        str(found and (found.get("status"), found.get("value"), found.get("unit"), found.get("reason"))),
    )
    partial = table(
        "\n".join([
            "Marketable securities: 2025=18763",
            "Marketable securities: 2025=77723",
            "Cash and cash equivalents: 2025=35934",
        ]),
        "AAPL",
    )
    record(
        "a partial marketable-securities row is not the combined total",
        resolve_narrative_question(APPLE, [partial], COMPANIES)["status"] == "insufficient",
    )
    other = narrative(
        "Microsoft had cash, cash equivalents and marketable securities, "
        "which totaled $10.0 billion as of September 27, 2025.",
        "MSFT",
    )
    wrong_company = resolve_narrative_question(APPLE, [other], COMPANIES)
    record(
        "another company's combined total is not used",
        wrong_company["status"] == "insufficient" and wrong_company.get("value") is None,
        str(wrong_company),
    )
    conflict = resolve_narrative_question(
        APPLE,
        [
            apple,
            narrative(
                "Balances of cash, cash equivalents and marketable securities "
                "totaled $100.0 billion as of September 27, 2025.",
                "AAPL",
                filing="other.txt",
            ),
        ],
        COMPANIES,
    )
    record(
        "disagreeing combined totals abstain",
        conflict["status"] == "insufficient",
        str(conflict.get("reason")),
    )

    tax = resolve_narrative_question(
        TAX,
        [narrative(TAX_SENTENCE + " " + RPO_SENTENCE, "MSFT")],
        COMPANIES,
    )
    record(
        "the IRS payment is not the commercial RPO amount",
        tax and tax["status"] == "answered" and tax["value"] == 28.9 and tax["unit"] == "billion",
        str(tax and (tax.get("status"), tax.get("value"), tax.get("reason"))),
    )
    rpo_only = resolve_narrative_question(TAX, [narrative(RPO_SENTENCE, "MSFT")], COMPANIES)
    record(
        "an unrelated RPO sentence does not answer the tax question",
        rpo_only["status"] == "insufficient",
        str(rpo_only.get("reason")),
    )

    aum = resolve_narrative_question(
        AUM,
        [narrative(FIRM_AUM + " " + PRODUCT_AUM, "TROW")],
        COMPANIES,
    )
    record(
        "firmwide assets under management are not the target-date figure",
        aum and aum["status"] == "answered" and aum["value"] == 1775.6 and aum["unit"] == "billion",
        str(aum and (aum.get("status"), aum.get("value"), aum.get("reason"))),
    )
    product_only = resolve_narrative_question(AUM, [narrative(PRODUCT_AUM, "TROW")], COMPANIES)
    record(
        "a product-level figure alone does not become the firmwide total",
        product_only["status"] == "insufficient",
        str(product_only.get("reason")),
    )
    ordinary = resolve_narrative_question(
        "What was Microsoft's total revenue for fiscal year 2026, in USD millions?",
        [narrative(TAX_SENTENCE + " " + RPO_SENTENCE, "MSFT")],
        COMPANIES,
    )
    record(
        "a statement-line question is left to table lookup",
        ordinary is None,
        str(ordinary),
    )
    untouched = [
        (
            "the commercial RPO question stays on the existing path",
            "What was Microsoft's commercial remaining performance obligation, in USD billions, in the fiscal year 2026 Form 10-K?",
            RPO_SENTENCE,
            "MSFT",
        ),
        (
            "the notes principal question stays on the existing path",
            "What was the aggregate principal amount of Apple's fixed-rate notes, in USD billions, as disclosed in the fiscal year 2025 Form 10-K?",
            "The aggregate principal amount of fixed-rate notes was $91.3 billion.",
            "AAPL",
        ),
        (
            "the repurchase question stays on the existing path",
            "On May 1, 2025, how large a share repurchase program did Apple announce, in USD billions?",
            "The Company announced an additional program to repurchase up to $100 billion of its common stock.",
            "AAPL",
        ),
    ]
    for name, question, sentence, ticker in untouched:
        found = resolve_narrative_question(question, [narrative(sentence, ticker)], COMPANIES)
        record(name, found is None, str(found))


class _Retriever:
    def __init__(self, tables, narratives):
        self.tables = tables
        self.narratives = narratives
        self.retrieve_called = False

    def get_table_chunks(self):
        return self.tables

    def get_narrative_chunks(self):
        return self.narratives

    def retrieve(self, question, top_k=5):
        self.retrieve_called = True
        return []


class _RAG:
    def __init__(self, tables, narratives):
        self.retriever = _Retriever(tables, narratives)


def test_pipeline_prefers_narrative_scope():
    rag = _RAG(
        [
            table(
                "Marketable securities: 2025=18763\nCash and cash equivalents: 2025=35934",
                "AAPL",
            )
        ],
        [narrative(APPLE_SENTENCE, "AAPL")],
    )
    pipeline = TAOPipeline(rag, company_index=COMPANIES, allow_external_fallback=False)
    answer = pipeline.run(APPLE)
    record(
        "pipeline does not abstain on the partial cash rows",
        "132.4 billion" in answer["answer"] and rag.retriever.retrieve_called is False,
        answer["answer"],
    )
    aum_rag = _RAG(
        [table("Assets under management: 2025=561.4", "TROW", scale="billion")],
        [narrative(FIRM_AUM + " " + PRODUCT_AUM, "TROW")],
    )
    aum_pipeline = TAOPipeline(aum_rag, company_index=COMPANIES, allow_external_fallback=False)
    aum_answer = aum_pipeline.run(AUM)
    record(
        "pipeline does not answer with the target-date table",
        "1,775.6 billion" in aum_answer["answer"] and "561.4" not in aum_answer["answer"],
        aum_answer["answer"],
    )


